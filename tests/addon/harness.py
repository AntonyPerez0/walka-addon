"""Python side of the addon test harness.

``WowRuntime`` owns one Lua 5.1 state with the mock client from
``lua/wow_env.lua`` in it, loads the addon the way the game does and lets a
test drive it: advance time, fire events, type slash commands, click
widgets, simulate a ``/reload`` - and read back what the addon painted,
printed and saved.

What exists in the mock client is decided by ``Snapshot``, the API snapshot
generated by ``tools/gen_api_snapshot.py``.
"""

from __future__ import annotations

import functools
import gzip
import json
import re
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from lupa.lua51 import LuaRuntime
from walka import beacon
from walka.protocol import Frame, StatFrame

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent
ADDON_DIR = REPO_ROOT / "Walka"
SNAPSHOT_PATH = HERE / "data" / "forever_api.json.gz"
ENV_SOURCE = HERE / "lua" / "wow_env.lua"

# The only globals the addon may create (frame names must start with "Walka").
ALLOWED_GLOBALS = {"Walka", "WalkaDB", "WalkaCharDB", "WalkaCompanionData", "SLASH_WALKA1", "Walka_OnCompartmentClick"}

# Globals the addon reads although this client does not have them, with the
# reason each read is fine. Keep this short: every entry is a place where the
# tests cannot tell a typo from a deliberate probe.
ALLOWED_UNDEFINED: dict[str, str] = {}


