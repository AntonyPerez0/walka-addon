# TOC
# ---------------------------------------------------------------------------


@dataclass
class Toc:
    name: str
    metadata: dict[str, str] = field(default_factory=dict)
    files: list[str] = field(default_factory=list)

    @property
    def saved_variables(self) -> list[str]:
        names: list[str] = []
        for key in ("SavedVariables", "SavedVariablesPerCharacter"):
            names += [name for name in re.split(r"[,\s]+", self.metadata.get(key, "")) if name]
        return names


def parse_toc(path: Path) -> Toc:
    toc = Toc(name=path.stem)
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("##"):
            match = re.match(r"##\s*([^:]+?)\s*:\s*(.*)$", line)
            if match:
                toc.metadata[match.group(1)] = match.group(2).strip()
        elif not line.startswith("#"):
            toc.files.append(line)
    return toc


