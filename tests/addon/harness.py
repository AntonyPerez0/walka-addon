class AddonError(AssertionError):
    """The addon reported an error to the client's error handler."""


class WowRuntime:
    """A mock WoW client with (optionally) the addon loaded into it."""

    def __init__(
        self,
        *,
        addon_dir: Path = ADDON_DIR,
        saved_variables: dict[str, str] | None = None,
        files: dict[str, str] | None = None,
        state: dict[str, Any] | None = None,
        snapshot: Snapshot | None = None,
    ):
        self.snapshot = snapshot or load_snapshot()
        self.addon_dir = Path(addon_dir)
        tocs = sorted(self.addon_dir.glob("*.toc"))
        if not tocs:
            raise FileNotFoundError(f"no .toc file in {self.addon_dir}")
        self.toc = parse_toc(tocs[0])
        self.addon_name = self.toc.name
        self.saved_variables = dict(saved_variables or {})
        self.files = dict(files or {})      # TOC path -> replacement source
        self.loaded_files: list[str] = []
        self.skipped_files: list[str] = []
        self.loaded = False

        self.lua = LuaRuntime(unpack_returned_tuples=True)
        load = self.lua.eval(
            "function(source, name, host) "
            "local chunk, err = loadstring(source, name) "
            "if not chunk then error(err, 0) end "
            "return chunk(host) end"
        )
        self.M = load(ENV_SOURCE.read_text(encoding="utf-8"), "@wowmock/wow_env.lua", self._host())
        self.G = self.M.G
        self.game = self.M.state
        self.log = self.M.log
        self.ns = self.M.new_table()
        for key, value in (state or {}).items():
            self.game[key] = value

    # ---- host callbacks (Lua -> snapshot) ------------------------------------
    def to_lua(self, value: Any) -> Any:
        """Convert Python containers to Lua tables (lists become arrays)."""
        if isinstance(value, dict):
            table = self.lua.table()
            for key, item in value.items():
                table[key] = self.to_lua(item)
            return table
        if isinstance(value, (list, tuple)):
            table = self.lua.table()
            for index, item in enumerate(value, start=1):
                table[index] = self.to_lua(item)
            return table
        if isinstance(value, (set, frozenset)):
            table = self.lua.table()
            for item in value:
                table[item] = True
            return table
        return value

    def _host(self):
        snapshot = self.snapshot
        to_lua = self.to_lua

        def optional(value):
            return None if value is None else to_lua(value)

        return self.lua.table_from(
            {
                "type_chain": lambda widget_type: optional(snapshot.type_chain(widget_type)),
                "type_methods": lambda widget_type: to_lua(snapshot.type_methods(widget_type)),
                "type_scripts": lambda widget_type: to_lua(snapshot.type_scripts(widget_type)),
                "native_type": snapshot.native_type,
                "template": lambda name: optional(snapshot.templates.get(name)),
                "frame": lambda name: optional(snapshot.frames.get(name)),
                "lod": snapshot.lod.get,
                "is_font": lambda name: name in snapshot.fonts,
                "is_event": lambda name: name in snapshot.events,
                "is_enum": lambda name: name in snapshot.enums,
                "members": lambda name: optional(snapshot.members.get(name)),
                "mixin_members": lambda name: optional(snapshot.mixin_members(name)),
                "namespace": lambda name: optional(snapshot.namespaces.get(name)),
                "global_kind": snapshot.global_kind,
            }
        )

    # ---- loading -------------------------------------------------------------
    def load_addon(self, *, reloading: bool = False) -> WowRuntime:
        """Load every file of the TOC in order, hand over the saved
        variables, then fire the start-up events - as the client does."""
        if self.loaded:
            raise RuntimeError("the addon is already loaded")
        self.M.addon.name = self.addon_name
        self.M.addon.toc = self.to_lua(self.toc.metadata)
        for name in self.toc.saved_variables:
            self.M.declare(name)
        for relative in self.toc.files:
            if relative in self.files:
                source = self.files[relative]
            else:
                path = self.addon_dir.joinpath(*re.split(r"[\\/]+", relative))
                if not path.is_file():
                    # Listed but not written yet: the game would log a
                    # warning and carry on.
                    self.skipped_files.append(relative)
                    continue
                source = path.read_text(encoding="utf-8-sig")
            chunk_name = f"{self.addon_name}/{relative.replace(chr(92), '/')}"
            self.M.load_file(source, chunk_name, self.addon_name, self.ns)
            self.loaded_files.append(relative)
        # Saved variables are loaded after the addon's files have run ...
        for name, source in self.saved_variables.items():
            self.M.set_global(name, self.M.deserialize(source))
        self.loaded = True
        # ... and just before ADDON_LOADED.
        self.fire_event("ADDON_LOADED", self.addon_name)
        self.fire_event("PLAYER_LOGIN")
        self.fire_event("PLAYER_ENTERING_WORLD", not reloading, reloading)
        return self

    def reload(self, *, gap: float = 0.0) -> WowRuntime:
        """Simulate /reload (or logging out and in again ``gap`` seconds
        later): the saved variables go through the client's serialiser and
        into a fresh Lua state. The game state carries over."""
        self.fire_event("PLAYER_LEAVING_WORLD")
        self.fire_event("PLAYER_LOGOUT")
        saved = {}
        for name in self.toc.saved_variables:
            source = self.M.serialize(name)
            if source is not None:
                saved[name] = source
        state = {key: value for key, value in self.game.items()}
        state["clock"] = state["clock"] + gap
        state["uptime"] = state["uptime"] + gap
        fresh = WowRuntime(
            addon_dir=self.addon_dir, saved_variables=saved, files=self.files, state=state, snapshot=self.snapshot
        )
        return fresh.load_addon(reloading=gap == 0.0)

    # ---- driving -------------------------------------------------------------
    def check_errors(self) -> None:
        errors = list(self.log.errors.values())
        if errors:
            for index in range(len(errors), 0, -1):
                self.log.errors[index] = None
            raise AddonError("the addon raised errors:\n  " + "\n  ".join(str(error) for error in errors))

    def fire_event(self, event: str, *args: Any) -> int:
        count = self.M.fire_event(event, *args)
        self.check_errors()
        return count

    def frame(self, elapsed: float) -> None:
        """One rendered frame of ``elapsed`` seconds."""
        self.M.run_frame(elapsed)
        self.check_errors()

    def advance(self, seconds: float, step: float = 0.1) -> None:
        """Let ``seconds`` pass in frames of ``step`` seconds (the default
        makes the addon tick once per frame)."""
        frames = int(round(seconds / step))
        for _ in range(frames):
            self.M.run_frame(step)
        self.check_errors()

    def tick(self, count: int = 1) -> None:
        """Exactly ``count`` addon ticks."""
        self.advance(count * 0.1, 0.1)

    def slash(self, text: str) -> None:
        self.M.slash(text)
        self.check_errors()

    def run(self, source: str, *args: Any) -> Any:
        """Run Lua test code inside the addon's environment (so it sees
        what the addon sees). ``...`` in the code are ``args``; the addon's
        private table is not a global, pass ``rt.ns`` if the code needs it."""
        result = self.M.run(source, *args)
        self.check_errors()
        return result

    def set(self, **values: Any) -> None:
        """Change the game state, e.g. ``rt.set(speed=7, mounted=True)``."""
        for key, value in values.items():
            self.game[key] = value

    def enter_combat(self, *, secret: bool = True) -> None:
        """Combat as Midnight clients have it: unit stats become secret."""
        self.set(combat=True, statsSecret=secret)

    def leave_combat(self) -> None:
        self.set(combat=False, statsSecret=False)

    # ---- reading back --------------------------------------------------------
    @property
    def printed(self) -> list[str]:
        return [str(line) for line in self.log.printed.values()]

    def clear_printed(self) -> None:
        for index in range(len(self.log.printed), 0, -1):
            self.log.printed[index] = None

    @property
    def reload_requests(self) -> int:
        """How often the addon has called ReloadUI(). The mock records the
        call and carries on in the same Lua state; ``reload()`` is what does
        to the addon what a reload does."""
        return len(self.log.reloads)

    def global_(self, name: str) -> Any:
        return self.M.get_global(name)

    @property
    def walka(self) -> Any:
        return self.ns.Walka

    @property
    def db(self) -> Any:
        return self.M.get_global("WalkaDB")

    def find_secrets(self) -> list[str]:
        """Paths of secret values reachable from the addon (should be [])."""
        return [str(path) for path in self.M.find_secrets(self.ns, "@" + self.addon_name + "/").values()]

    def undefined_globals(self) -> dict[str, int]:
        return {str(name): int(count) for name, count in self.log.undefined.items()}

    def created_globals(self) -> set[str]:
        return {str(name) for name in self.log.created.keys()}

    def keys(self, table: Any) -> set[str]:
        return {str(key) for key in table.keys()}

    def inspect(self, widget: Any) -> dict[str, Any]:
        info = self.M.inspect(widget)
        if info is None:
            raise TypeError("not a widget")
        return dict(info.items())

    # ---- widgets ---------------------------------------------------------------
    def descendants(self, root: Any, widget_type: str | None = None, *, visible: bool | None = None) -> list[Any]:
        """Widgets below ``root`` (itself included), optionally of one type
        and/or by visibility, in creation order."""
        return lua_list(self.M.descendants(root, widget_type, visible))

    def texts(self, root: Any = None) -> list[str]:
        """The texts of the visible font strings below ``root``."""
        return [str(text) for text in lua_list(self.M.visible_texts(root))]

    def click(self, widget: Any, button: str = "LeftButton") -> bool:
        clicked = self.M.click(widget, button)
        self.check_errors()
        return bool(clicked)

    def hover(self, widget: Any) -> None:
        """Move the mouse over a widget and away again (tooltips)."""
        self.M.hover(widget, True)
        self.M.hover(widget, False)
        self.check_errors()

    # ---- the beacon, as the companion sees it ---------------------------------
    def beacon_frame(self) -> Any:
        frame = self.M.get_global("WalkaBeaconFrame")
        if frame is None:
            raise AssertionError("the addon has not created WalkaBeaconFrame")
        return frame

    def beacon_textures(self) -> list[dict[str, Any]]:
        """The strip's textures with their on-screen geometry, back to front."""
        textures = [self.inspect(region) for region in self.M.regions(self.beacon_frame()).values()]
        layers = dict(self.M.draw_layers.items())
        textures.sort(key=lambda t: (layers[t["layer"]], t["subLevel"] or 0, t["serial"]))
        return textures

    def beacon_cells(self) -> list[int]:
        """The cell values painted right now (1 = white), left to right,
        read from the textures the addon coloured."""
        cells = [t for t in self.beacon_textures() if t["layer"] == "OVERLAY"]
        cells.sort(key=lambda t: t["left"])
        values = []
        for cell in cells:
            red, green, blue, alpha = (cell["color"][i] for i in (1, 2, 3, 4))
            if not (red == green == blue) or red not in (0, 1) or alpha != 1:
                raise AssertionError(f"beacon cell is not pure black or white: {(red, green, blue, alpha)}")
            values.append(int(red))
        return values

    def shown_frame(self) -> Frame | StatFrame:
        """What the strip shows right now, decoded with the companion's
        decoder: a live frame or - on every fifth redraw - a stat frame."""
        return beacon.decode_cells(self.beacon_cells())

    def live_frame(self) -> Frame:
        """The live frame on the strip, as the companion's belt control
        reads it.

        Every fifth redraw carries one number of the character's journey
        instead (a stat frame, docs/PROTOCOL.md section 4), which the belt
        control ignores: it goes by the next live frame, a tenth of a second
        later. So does this - if a stat frame is showing, one more tick is
        let pass. (Two stat frames never follow each other.)"""
        frame = self.shown_frame()
        if isinstance(frame, StatFrame):
            self.tick()
            frame = self.shown_frame()
        assert isinstance(frame, Frame), "two stat frames in a row"
        return frame

    def render_beacon_row(
        self,
        row: int = 0,
        *,
        width: int | None = None,
        background: int | Iterable[int] = 0,
    ) -> bytes:
        """Rasterise one physical pixel row of the game window where the
        beacon is, from the sizes, offsets and scale the addon really set.

        ``background`` is the brightness of the game world behind the strip
        (a constant or one value per pixel). A pixel takes a texture's colour
        when its centre lies inside the texture, as a GPU would decide.
        """
        game = self.game
        physical_width, physical_height = int(game.physicalWidth), int(game.physicalHeight)
        width = width or physical_width
        if isinstance(background, int):
            pixels = [background] * width
        else:
            pixels = list(background)[:width]
        frame = self.inspect(self.beacon_frame())
        if not frame["visible"]:
            return bytes(pixels)
        unit = physical_height / 768.0        # physical pixels per screen unit
        center_y = row + 0.5
        for texture in self.beacon_textures():
            if not texture["visible"] or texture["color"] is None or texture["left"] is None:
                continue
            alpha = texture["alpha"] * texture["color"][4]
            if alpha <= 0:
                continue
            left = texture["left"] * unit
            right = left + texture["width"] * unit
            top = physical_height - (texture["bottom"] + texture["height"]) * unit
            bottom = physical_height - texture["bottom"] * unit
            if not top <= center_y < bottom:
                continue
            brightness = 255 * texture["color"][1]
            for x in range(max(0, int(left) - 1), min(width, int(right) + 2)):
                if left <= x + 0.5 < right:
                    pixels[x] = int(round(brightness * alpha + pixels[x] * (1 - alpha)))
        return bytes(pixels)


def lua_list(table: Any) -> list[Any]:
    """A Lua array as a Python list."""
    return [table[index] for index in range(1, len(table) + 1)]


def lua_dict(table: Any) -> dict[Any, Any]:
    """A Lua table as a (shallow) Python dict."""
    return dict(table.items())


def lua_plain(value: Any) -> Any:
    """A Lua value as plain Python data (deep): arrays become lists."""
    if hasattr(value, "items") and hasattr(value, "keys") and not isinstance(value, dict):
        keys = list(value.keys())
        if keys and all(isinstance(key, int) for key in keys) and sorted(keys) == list(range(1, len(keys) + 1)):
            return [lua_plain(value[index]) for index in range(1, len(keys) + 1)]
        return {key: lua_plain(item) for key, item in value.items()}
    return value
