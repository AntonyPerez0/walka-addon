class Snapshot:
    """What exists in the WoW: Forever client (see tools/gen_api_snapshot.py)."""

    def __init__(self, path: Path = SNAPSHOT_PATH):
        with gzip.open(path, "rb") as stream:
            data = json.loads(stream.read().decode("ascii"))
        self.data = data
        self.meta = data["meta"]
        api = data["api"]
        self.api_globals: frozenset[str] = frozenset(api["globals"])
        self.namespaces: dict[str, frozenset[str]] = {ns: frozenset(fns) for ns, fns in api["namespaces"].items()}
        self.secret: dict[str, list[str]] = api["secret"]
        self.protected: frozenset[str] = frozenset(api["protected"])
        self.restricted: frozenset[str] = frozenset(api["restricted"])
        self.c_globals: frozenset[str] = frozenset(data["c_globals"])
        self.events: frozenset[str] = frozenset(data["events"])
        self.enums: frozenset[str] = frozenset(data["enums"])
        self.toc_fields: frozenset[str] = frozenset(data["toc_fields"])
        self.fonts: frozenset[str] = frozenset(data["fonts"])
        self.frames: dict[str, dict] = data["frames"]
        self.templates: dict[str, dict] = data["templates"]
        self.lua_functions: frozenset[str] = frozenset(data["lua"]["functions"])
        self.lua_values: frozenset[str] = frozenset(data["lua"]["values"])
        self.referenced: frozenset[str] = frozenset(data["referenced"])
        self.members: dict[str, list[str]] = data["members"]
        self.mixin_parents: dict[str, list[str]] = data["mixin_parents"]
        self.lod: dict[str, str] = data["lod"]
        widgets = data["widgets"]
        self.widget_apis: dict[str, list[str]] = widgets["apis"]
        self.widget_types: dict[str, dict] = widgets["types"]
        self.widget_scripts: dict[str, list[str]] = widgets["scripts"]
        self.tooltip_methods: frozenset[str] = frozenset(widgets["tooltip_methods"])
        self._methods: dict[str, frozenset[str]] = {}

    # ---- widgets -----------------------------------------------------------
    def type_chain(self, widget_type: str) -> list[str] | None:
        """The widget type and its ancestors, nearest first."""
        if widget_type not in self.widget_types:
            return None
        chain = []
        current: str | None = widget_type
        while current is not None:
            chain.append(current)
            current = self.widget_types[current]["parent"]
        return chain

    def type_methods(self, widget_type: str) -> frozenset[str]:
        methods = self._methods.get(widget_type)
        if methods is None:
            found: set[str] = set()
            for ancestor in self.type_chain(widget_type) or []:
                for api in self.widget_types[ancestor]["apis"]:
                    found.update(self.widget_apis[api])
            if widget_type == "GameTooltip":
                found |= self.tooltip_methods
            methods = frozenset(found)
            self._methods[widget_type] = methods
        return methods

    def type_scripts(self, widget_type: str) -> frozenset[str]:
        return frozenset(self.widget_scripts.get(widget_type, ()))

    def native_type(self, tag: str) -> str | None:
        """The widget type behind an XML tag: itself, or an intrinsic's base."""
        for _ in range(8):
            if tag in self.widget_types:
                return tag
            template = self.templates.get(tag)
            if not (template and template.get("x")):
                return None
            tag = template["t"]
        return None

    def is_frame_type(self, tag: str) -> bool:
        native = self.native_type(tag)
        return native is not None and "Frame" in (self.type_chain(native) or [])

    # ---- mixins ------------------------------------------------------------
    def mixin_members(self, mixin: str, _seen: frozenset[str] = frozenset()) -> dict[str, str] | None:
        """{method: mixin that defines it}, parents first so that the mixin's
        own methods win."""
        if mixin in _seen:
            return None
        own = self.members.get(mixin)
        parents = self.mixin_parents.get(mixin, [])
        if own is None and not parents:
            return None
        result: dict[str, str] = {}
        for parent in parents:
            result.update(self.mixin_members(parent, _seen | {mixin}) or {})
        for name in own or []:
            result[name] = mixin
        return result

    # ---- globals -----------------------------------------------------------
    def global_kind(self, name: str) -> str | None:
        """How a global name exists in this client at login, or None."""
        if name == "Enum":
            return "enum_root"
        if name in self.frames:
            return "frame"
        if name in self.fonts:
            return "font"
        if name in self.namespaces:
            return "namespace"
        if name in self.api_globals:
            return "api"
        if name in self.lua_functions:
            return "lua_function"
        if name in self.lua_values:
            return "lua_value"
        if name in self.c_globals:
            return "c"
        if name in self.referenced:
            return "referenced"
        if name in self.lod:
            return "lod:" + self.lod[name]
        return None

    def knows_global(self, name: str) -> bool:
        kind = self.global_kind(name)
        return kind is not None and not kind.startswith("lod:")

    def knows_member(self, dotted: str) -> bool:
        """Is ``Table.member`` something this client has?"""
        table, _, member = dotted.partition(".")
        if table in self.namespaces and member in self.namespaces[table]:
            return True
        if table == "Enum":
            return member in self.enums
        return member in self.members.get(table, ())


@functools.lru_cache(maxsize=1)
def load_snapshot() -> Snapshot:
    return Snapshot()


